// Storing a demo or pipeline test recording (spec 31.2, 34, 63, 80).
//
// The recording is stored with the same integrity as research audio: validated
// from its bytes, hashed, written to private storage, and linked as the accepted
// recording of a submitted utterance, which the database then keeps immutable.
// It is never research data: the session has mode `demo` or `test`.
//
// Data model mapping, inside the frozen schema:
// - one task_presentations row per session. It points at a carrier task of the
//   session's protocol (the free speech task when there is one), because the
//   column is a required foreign key. The snapshot texts say that this is a
//   demo or test recording, not the task text;
// - one utterances row per recording, with turn_index 0, 1, 2, ...;
// - one media_assets row per recording, kind source_audio (lossless WAV) or
//   source_audio_raw (compressed fallback).
//
// This code does not use the participant task flow, which enforces the research
// sequence (consent, microphone check, instructions, task order).
import { randomUUID } from "node:crypto";
import { and, asc, eq, sql } from "drizzle-orm";
import {
  mediaAssets,
  protocolTasks,
  sessions as sessionsTable,
  taskPresentations,
  utterances,
  type MediaMetadata,
  type Transaction,
  type UtteranceQuality,
} from "@dialect/db";
import { AppError, isAppError, sessionSchemas, type demoSchemas } from "@dialect/domain";
import { computeWavQuality, sha256OfBuffer, sourceAudioKey, validateUploadedAudio } from "@dialect/storage";
import type { ServiceContext } from "../context";
import { deleteStoredObjects, isTerminalStatus, lockSession, type SessionRow } from "../sessions/internal";
import { DURATION_GRACE_SECONDS } from "../sessions/tasks";
import { demoAcknowledgementOf } from "./session";

export type DemoRecordingInput = {
  data: Buffer;
  // Content type sent by the browser. Stored as declared metadata only.
  declaredMimeType?: string | null;
  captureMetadata?: sessionSchemas.CaptureMetadata | null;
};

export type StoredRecording = {
  utteranceId: string;
  taskPresentationId: string;
  turnIndex: number;
  mediaAssetId: string;
  storageKey: string;
  source: demoSchemas.PipelineSourceInfo;
  // Time of the storage write and its check, for the Storage row of the pipeline test.
  storageWriteMs: number;
};

const PRESENTATION_TEXT = {
  demo: {
    title: "Demo recording",
    prompt: "Demo Mode recording. The speaker chose what to say. This is not a study task.",
    instructions:
      "Recorded on the demo page for a demonstration. Demo data, not research data. The linked protocol task is only a carrier and was not shown.",
  },
  test: {
    title: "Pipeline test recording",
    prompt: "Admin pipeline test recording. This is not a study task.",
    instructions:
      "Recorded or generated by the admin pipeline test. Test data, not research data. The linked protocol task is only a carrier and was not shown.",
  },
} as const;

type RecordingMode = keyof typeof PRESENTATION_TEXT;

async function loadTarget(tx: Transaction, sessionId: string, allowed: RecordingMode) {
  const locked = await lockSession(tx, sessionId);
  if (locked.session.mode !== allowed) {
    throw new AppError("FORBIDDEN", `This recording path is only available for a ${allowed} session.`, {
      mode: locked.session.mode,
    });
  }
  if (isTerminalStatus(locked.session.status)) {
    throw new AppError("SESSION_EXPIRED", "The session has ended. Please start again.");
  }
  return locked;
}

// The task the presentation row points at: the free speech task of the pinned
// protocol, or the first enabled task when the protocol has none.
async function carrierTaskId(tx: Transaction, protocolVersionId: string): Promise<string> {
  const tasks = await tx
    .select({ id: protocolTasks.id, taskType: protocolTasks.taskType })
    .from(protocolTasks)
    .where(and(eq(protocolTasks.protocolVersionId, protocolVersionId), eq(protocolTasks.enabled, true)))
    .orderBy(asc(protocolTasks.orderIndex));
  const carrier = tasks.find((task) => task.taskType === "free_speech") ?? tasks[0];
  if (!carrier) {
    throw new AppError(
      "CONFIGURATION_MISSING",
      "The current protocol has no enabled task. A demo recording needs one task to attach to.",
    );
  }
  return carrier.id;
}

async function ensurePresentation(tx: Transaction, session: SessionRow, mode: RecordingMode, now: Date) {
  const [existing] = await tx
    .select()
    .from(taskPresentations)
    .where(eq(taskPresentations.sessionId, session.id))
    .orderBy(asc(taskPresentations.sequenceIndex))
    .limit(1);
  if (existing) return existing;
  const text = PRESENTATION_TEXT[mode];
  const [created] = await tx
    .insert(taskPresentations)
    .values({
      sessionId: session.id,
      protocolTaskId: await carrierTaskId(tx, session.protocolVersionId),
      sequenceIndex: 0,
      titleSnapshot: text.title,
      promptSnapshot: text.prompt,
      contextSnapshot: null,
      instructionsSnapshot: text.instructions,
      status: "started",
      startedAt: now,
    })
    .returning();
  if (!created) throw new AppError("DATABASE_ERROR", "The recording could not be attached to the session.");
  return created;
}

const SAVE_FAILED = "The recording could not be saved. Please try again.";

// Validates and stores one recording and inserts its rows. Used by Demo Mode
// (mode demo) and by the pipeline test (mode test).
export async function storeSessionRecording(
  ctx: ServiceContext,
  session: Pick<SessionRow, "id">,
  input: DemoRecordingInput,
  // `limits` lowers the limits of the study settings (maxUtteranceSeconds,
  // maxUploadMb). It never raises them.
  options: { mode: RecordingMode; limits?: { maxDurationSeconds: number; maxBytes: number } },
): Promise<StoredRecording> {
  const target = await ctx.db.transaction((tx) => loadTarget(tx, session.id, options.mode));
  const { study, settings } = target;

  // Nothing the browser claims about the file is trusted (spec 63). Demo Mode
  // accepts lossless WAV and the compressed fallback (spec 31.2).
  const validated = await validateUploadedAudio({
    data: input.data,
    declaredMimeType: input.declaredMimeType ?? undefined,
    maxBytes: Math.min(options.limits?.maxBytes ?? Infinity, settings.maxUploadMb * 1024 * 1024),
    maxDurationSeconds:
      Math.min(options.limits?.maxDurationSeconds ?? Infinity, settings.maxUtteranceSeconds) + DURATION_GRACE_SECONDS,
  });
  const sha256 = sha256OfBuffer(input.data);

  let quality: UtteranceQuality | null = null;
  if (validated.container === "wav") {
    try {
      quality = computeWavQuality(input.data);
    } catch {
      quality = null;
    }
  }

  const utteranceId = randomUUID();
  const assetId = randomUUID();
  const storageKey = sourceAudioKey({
    studySlug: study.slug,
    sessionId: target.session.id,
    utteranceId,
    assetId,
    extension: validated.extension,
  });

  const writeStarted = performance.now();
  try {
    const stored = await ctx.storage.put({ key: storageKey, body: input.data, contentType: validated.mimeType });
    if (stored.sha256 !== sha256 || stored.sizeBytes !== input.data.length) {
      throw new Error("The stored object does not match the uploaded bytes.");
    }
    if (!(await ctx.storage.exists(storageKey))) throw new Error("The stored object cannot be read back.");
  } catch (error) {
    await deleteStoredObjects(ctx, [storageKey]);
    throw new AppError("UPLOAD_FAILED", SAVE_FAILED, { stage: "storage" }, { cause: error });
  }
  const storageWriteMs = Math.max(0, Math.round(performance.now() - writeStarted));

  const capture = input.captureMetadata ?? {};
  // Device identifiers and the raw device label are never stored (spec 6.2).
  // The request schema already removes them. This is the second layer.
  const metadata: MediaMetadata = {
    ...(capture.requestedConstraints
      ? { requestedConstraints: sessionSchemas.stripDeviceIdentifiers(capture.requestedConstraints) }
      : {}),
    ...(capture.actualTrackSettings
      ? { actualTrackSettings: sessionSchemas.stripDeviceIdentifiers(capture.actualTrackSettings) }
      : {}),
    ...(capture.audioContextSampleRate ? { audioContextSampleRate: capture.audioContextSampleRate } : {}),
    ...(capture.userAgent ? { browserUserAgent: capture.userAgent } : {}),
    probe: validated.probe,
    // What the browser said about the file. Never used as the technical truth.
    declared: {
      mimeType: input.declaredMimeType ?? null,
      mimeTypeMatches: validated.declaredMimeTypeMatches,
      durationMs: capture.declaredDurationMs ?? null,
      sampleRateHz: capture.declaredSampleRateHz ?? null,
      channels: capture.declaredChannels ?? null,
      ...(capture.declaredBitDepth !== undefined ? { bitDepth: capture.declaredBitDepth } : {}),
      ...(capture.deviceLabel !== undefined
        ? { deviceLabel: sessionSchemas.toInputDeviceClass(capture.deviceLabel) }
        : {}),
      ...(capture.constraintMismatches !== undefined ? { constraintMismatches: capture.constraintMismatches } : {}),
      ...(capture.fallbackReason !== undefined ? { fallbackReason: capture.fallbackReason } : {}),
      ...(capture.fallbackDetail !== undefined ? { fallbackDetail: capture.fallbackDetail } : {}),
      ...(capture.peak !== undefined ? { peak: capture.peak } : {}),
      ...(capture.stoppedBy !== undefined ? { stoppedBy: capture.stoppedBy } : {}),
    },
    ...(quality ? { quality } : {}),
    recordingPath: options.mode === "demo" ? "demo_mode" : "pipeline_test",
  };
  const kind = validated.captureQualityClass === "lossless_pcm" ? "source_audio" : "source_audio_raw";

  try {
    const stored = await ctx.db.transaction(async (tx) => {
      // The session may have ended while the file was validated and stored.
      const again = await loadTarget(tx, session.id, options.mode);
      const now = ctx.now();
      const presentation = await ensurePresentation(tx, again.session, options.mode, now);
      const [last] = await tx
        .select({ value: sql<number | null>`max(${utterances.turnIndex})` })
        .from(utterances)
        .where(eq(utterances.taskPresentationId, presentation.id));
      const turnIndex = last?.value === null || last?.value === undefined ? 0 : Number(last.value) + 1;

      // The utterance and its media row refer to each other. Order: the
      // utterance without its recording, the media row, then the link, which
      // also makes the utterance `submitted` and therefore immutable.
      await tx.insert(utterances).values({
        id: utteranceId,
        sessionId: again.session.id,
        taskPresentationId: presentation.id,
        followupId: null,
        promptSnapshot: PRESENTATION_TEXT[options.mode].prompt,
        turnIndex,
        status: "uploading",
      });
      await tx.insert(mediaAssets).values({
        id: assetId,
        studyId: study.id,
        sessionId: again.session.id,
        utteranceId,
        entityType: "utterance",
        entityId: utteranceId,
        kind,
        storageDriver: ctx.storage.driver,
        storageKey,
        mimeType: validated.mimeType,
        container: validated.container,
        codec: validated.codec,
        sampleRateHz: validated.sampleRateHz,
        channels: validated.channels,
        bitDepth: validated.bitDepth,
        durationMs: validated.durationMs,
        sizeBytes: validated.sizeBytes,
        sha256,
        captureMethod: capture.captureMethod ?? (validated.container === "wav" ? "audio_worklet_pcm" : "media_recorder"),
        captureQualityClass: validated.captureQualityClass,
        metadataJson: metadata,
        createdAt: now,
      });
      await tx
        .update(utterances)
        .set({
          acceptedMediaAssetId: assetId,
          status: "submitted",
          submittedAt: now,
          durationMs: validated.durationMs,
          qualityJson: quality,
        })
        .where(eq(utterances.id, utteranceId));
      await tx
        .update(sessionsTable)
        .set({ status: "recording", lastActivityAt: now })
        .where(eq(sessionsTable.id, again.session.id));
      return { presentationId: presentation.id, turnIndex };
    });

    return {
      utteranceId,
      taskPresentationId: stored.presentationId,
      turnIndex: stored.turnIndex,
      mediaAssetId: assetId,
      storageKey,
      source: {
        mediaAssetId: assetId,
        mimeType: validated.mimeType,
        durationMs: validated.durationMs,
        sizeBytes: validated.sizeBytes,
        sha256,
        captureQualityClass: validated.captureQualityClass,
      },
      storageWriteMs,
    };
  } catch (error) {
    await deleteStoredObjects(ctx, [storageKey]);
    if (isAppError(error)) throw error;
    throw new AppError("UPLOAD_FAILED", SAVE_FAILED, { stage: "database" }, { cause: error });
  }
}

// Stores one recording of a demo session as a submitted utterance with its
// accepted media asset. The visitor must have accepted the recording notice
// when the session was started.
export async function createDemoUtterance(
  ctx: ServiceContext,
  session: Pick<SessionRow, "id">,
  input: DemoRecordingInput,
): Promise<StoredRecording> {
  const [row] = await ctx.db.select().from(sessionsTable).where(eq(sessionsTable.id, session.id)).limit(1);
  if (!row) throw new AppError("SESSION_EXPIRED", "The demo session was not found. Please start again.");
  if (row.mode !== "demo") {
    throw new AppError("FORBIDDEN", "This recording path is only available for a demo session.", { mode: row.mode });
  }
  if (!demoAcknowledgementOf(row)) {
    throw new AppError("FORBIDDEN", "The recording notice must be accepted before a demo recording.", {
      reason: "demo_notice_not_accepted",
    });
  }
  // The limits of the study settings apply, as for a recording of the study.
  return storeSessionRecording(ctx, row, input, { mode: "demo" });
}
